window.SCHOOL_COUNT = window.SCHOOLS.reduce((a, [, l]) => a + l.length, 0)

/** 渲染“可搜索的院校选择器”：搜索框 + 分组原生下拉（移动端调用系统滚轮）+ 其他手填 */
window.schoolPicker = (name = 'school', value = '') => {
  const groups = window.SCHOOLS.map(([g, l]) => `<optgroup label="${g}">${l.map((s) => `<option ${s === value ? 'selected' : ''}>${s}</option>`).join('')}</optgroup>`).join('')
  return `<div class="school-picker" data-name="${name}">
    <input class="input sp-q" type="search" placeholder="搜索院校（中英文均可，共 ${window.SCHOOL_COUNT} 所）" autocomplete="off">
    <select class="input sp-sel" name="${name}"><option value="">请选择毕业院校</option>${groups}<option value="__other">其他院校（手动填写）</option></select>
    <input class="input sp-other" name="${name}_other" placeholder="请输入院校全称" style="display:none">
  </div>`
}
window.bindSchoolPicker = (root) => {
  root.querySelectorAll('.school-picker').forEach((p) => {
    const q = p.querySelector('.sp-q'), sel = p.querySelector('.sp-sel'), other = p.querySelector('.sp-other')
    const all = [...sel.querySelectorAll('optgroup')].map((g) => ({ g, opts: [...g.children] }))
    q.oninput = () => {
      const k = q.value.trim().toLowerCase()
      let first = null
      all.forEach(({ g, opts }) => { let n = 0; opts.forEach((o) => { const hit = !k || o.textContent.toLowerCase().includes(k); o.hidden = !hit; o.disabled = !hit; if (hit) { n++; first = first || o } }); g.hidden = !n })
      if (k && first) sel.value = first.value
      sel.onchange()
    }
    sel.onchange = () => { other.style.display = sel.value === '__other' ? '' : 'none' }
  })
}
window.schoolValue = (form, name = 'school') => {
  const v = form[name] && form[name].value
  return v === '__other' ? (form[name + '_other'].value || '').trim() : v
}
