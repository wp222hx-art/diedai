P=[]
def clean(b):
    b=re.sub(r'\n?，时长\n[\d:]+\n','\n',b)
    b=re.sub(r'(扫码添加订阅号|关注筑梦未来|我们将会助您梦想成真|^END$|排版：.*)','',b,flags=re.M)
    lines=[l.strip() for l in b.split('\n')]
    out=[];blank=0
    for l in lines:
        if not l: blank+=1; continue
        if out and blank: out.append('')
        out.append(l); blank=0
    return '\n'.join(out).strip()
